const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true,channel:"msedge"});
  const context = await browser.newContext({viewport:{width:1440,height:1100}});
  const page = await context.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8000/',{waitUntil:'networkidle'});
  await page.locator('.event-card').first().waitFor();
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  await page.locator('#auth-button').click();
  await page.locator('input[name=username]').fill('demo');
  await page.locator('input[name=password]').fill('SeatLock-demo-2026!');
  await page.locator('#auth-submit').click();
  await page.locator('#auth-dialog').waitFor({state:'hidden'});
  await page.locator('.event-card button').first().click();
  await page.locator('.seat:not(:disabled)').first().click();
  const seatLabel=await page.locator('.seat.selected').innerText();
  await page.locator('#reserve-button').click();
  await page.locator('#countdown').waitFor({state:'visible'});
  const other=await browser.newPage();
  await other.goto('http://127.0.0.1:8000/');
  await other.locator('.event-card button').first().click();
  await other.locator('.seat.held').filter({hasText:seatLabel}).waitFor();
  await page.reload();
  await page.locator('#countdown').waitFor({state:'visible'});
  await page.screenshot({path:'artifacts/seat-map.png',fullPage:true});
  await page.locator('#pay-button').click();
  await page.waitForFunction(()=>document.getElementById('selection-title').textContent==="You're going!",{timeout:20000});
  await page.locator('#bookings-nav').click();
  await page.locator('.booking-card').first().waitFor();
  await page.screenshot({path:'artifacts/bookings.png',fullPage:true});
  await page.locator('#explore-nav').click();
  await page.locator('.event-card button').first().click();
  await page.locator('.seat:not(:disabled)').first().click();
  await page.locator('#reserve-button').click();
  await page.locator('#countdown').waitFor({state:'visible'});
  await page.locator('#cancel-button').click();
  await page.locator('#countdown').waitFor({state:'hidden'});
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  await mobile.goto('http://127.0.0.1:8000/',{waitUntil:'networkidle'});
  await mobile.locator('.event-card').first().waitFor();
  await mobile.screenshot({path:'artifacts/mobile.png',fullPage:true});
  const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow)throw new Error('Mobile page overflows horizontally');
  if(errors.length)throw new Error(JSON.stringify(errors));
  fs.writeFileSync('artifacts/browser-test.json',JSON.stringify({passed:true,seatLabel,checks:[
    'event listing','sign in','seat reservation','second browser sees hold','reload restores hold',
    'background payment confirms booking','booking history','cancellation','mobile layout','no page errors']},null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
